"""กฎความปลอดภัยที่ทำงาน *ก่อน* ส่งข้อความให้ LLM (ไม่พึ่งให้ LLM ตัดสินเอง)

หมายเหตุ: ตรวจเบอร์โทรด่วนให้ถูกต้องกับแหล่งทางการก่อนใช้งานจริง
"""
import re

EMS_NUMBER = "1669"          # การแพทย์ฉุกเฉิน
MENTAL_HEALTH_HOTLINE = "1323"  # สายด่วนสุขภาพจิต

_SELF_HARM = re.compile(r"อยากตาย|ฆ่าตัวตาย|ทำร้ายตัวเอง|ไม่อยากมีชีวิต")
_EMERGENCY = re.compile(
    r"หายใจไม่ออก|หายใจลำบาก|แน่นหน้าอก|หมดสติ|ชัก|เป็นลม|"
    r"แพ้ยา|ผื่นขึ้นทั้งตัว|หน้าบวม|ปากบวม|ลิ้นบวม|คอบวม|"
    r"กินยาเกิน|กินยาผิด|กินยาไปเยอะ|ทานยาเกิน|อาเจียนเป็นเลือด|ถ่ายเป็นเลือด"
)

SELF_HARM_REPLY = (
    "ขอบคุณที่บอกนะคะ เรื่องนี้สำคัญมาก และคุณไม่ต้องรับมือคนเดียว\n"
    f"กรุณาโทรสายด่วนสุขภาพจิต {MENTAL_HEALTH_HOTLINE} ได้ตลอด หรือบอกคนใกล้ตัวให้อยู่เป็นเพื่อนตอนนี้\n"
    f"หากรู้สึกว่าไม่ปลอดภัยทันที โทร {EMS_NUMBER}"
)
EMERGENCY_REPLY = (
    "⚠️ อาการที่เล่ามาอาจเป็นเรื่องเร่งด่วน\n"
    f"กรุณาโทร {EMS_NUMBER} หรือไปโรงพยาบาลที่ใกล้ที่สุดทันที "
    "และนำกล่องหรือซองยาที่กินไปด้วย\n"
    "ระหว่างนี้อย่าเพิ่งกินยาเพิ่ม"
)


def check_emergency(text: str) -> str | None:
    """คืนข้อความตอบกลับสำเร็จรูปถ้าเข้าข่ายฉุกเฉิน ไม่เช่นนั้นคืน None"""
    if _SELF_HARM.search(text):
        return SELF_HARM_REPLY
    if _EMERGENCY.search(text):
        return EMERGENCY_REPLY
    return None
